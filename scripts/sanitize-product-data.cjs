const fs = require('fs');
const path = require('path');

const inputFile = path.join(__dirname, '..', 'src', 'data', 'productDetails.ts');
const outputFile = path.join(__dirname, '..', 'src', 'data', 'productDetails.clean.ts');

const content = fs.readFileSync(inputFile, 'utf8');

const catStart = content.indexOf('export const dynamicCategories: DynamicCategory[] = [');
const prodStart = content.indexOf('export const dynamicProducts: DynamicProduct[] = [');

if (catStart === -1 || prodStart === -1) {
  console.error("Could not find exports.");
  process.exit(1);
}

const catEquals = content.indexOf('=', catStart);
const catBracket = content.indexOf('[', catEquals);
let catString = content.substring(catBracket, prodStart).trim();
if (catString.endsWith(';')) {
  catString = catString.slice(0, -1);
}

const prodEquals = content.indexOf('=', prodStart);
const prodBracket = content.indexOf('[', prodEquals);
let prodString = content.substring(prodBracket).trim();
if (prodString.endsWith(';')) {
  prodString = prodString.slice(0, -1);
}

const dynamicCategories = JSON.parse(catString);
const dynamicProducts = JSON.parse(prodString);

function sanitizeString(str) {
  return str
    .replace(/Champak Steel & Engg\. Co\./gi, 'Vedantara Metal & Alloys')
    .replace(/Champak Steel and Engg\. Co\./gi, 'Vedantara Metal & Alloys')
    .replace(/Champak Steel House/gi, 'Vedantara Metal & Alloys')
    .replace(/Champak Steel/gi, 'Vedantara Metal & Alloys')
    .replace(/Champak steel/gi, 'Vedantara Metal & Alloys')
    .replace(/champaksteel\.com/gi, 'vedantarametal.com')
    .replace(/Champak/gi, 'Vedantara');
}

function processDescription(descArray) {
  if (!Array.isArray(descArray)) return descArray;
  
  return descArray
    .filter(str => {
      if (typeof str === 'string' && /Shankar Mansion/i.test(str)) {
        return false;
      }
      return true;
    })
    .map(str => {
      if (typeof str === 'string') {
        return sanitizeString(str);
      }
      return str;
    });
}

dynamicProducts.forEach(product => {
  if (product.description) {
    product.description = processDescription(product.description);
  }
  
  if (product.tables) {
    product.tables.forEach(table => {
      if (table.rows) {
        table.rows = table.rows.map(row => {
          return row.map(cell => {
            if (typeof cell === 'string') {
              if (/Shankar Mansion/i.test(cell)) {
                return "REMOVE_ME_FLAG";
              }
              return sanitizeString(cell);
            }
            return cell;
          }).filter(cell => cell !== "REMOVE_ME_FLAG");
        });
      }
    });
  }
});

dynamicCategories.forEach(cat => {
  if (cat.description) {
    cat.description = processDescription(cat.description);
  }
});

const newContent = `// AUTOGENERATED - DO NOT EDIT MANUALLY
export interface ProductLink {
  name: string;
  slug: string;
}

export interface Subcategory {
  name: string;
  productLinks: ProductLink[];
}

export interface DynamicCategory {
  title: string;
  slug: string;
  subcategories: Subcategory[];
}

export interface ProductTable {
  title?: string;
  rows: string[][];
}

export interface DynamicProduct {
  categorySlug: string;
  subCategoryName: string;
  productName: string;
  slug: string;
  description: string[];
  tables: ProductTable[];
  image?: string;
  images?: string[];
}

export const dynamicCategories: DynamicCategory[] = ${JSON.stringify(dynamicCategories, null, 2)};
export const dynamicProducts: DynamicProduct[] = ${JSON.stringify(dynamicProducts, null, 2)};
`;

fs.writeFileSync(outputFile, newContent);
console.log("Sanitization complete. File written to productDetails.clean.ts");
